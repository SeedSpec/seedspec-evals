#!/usr/bin/env node

import { cp, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { basename, resolve } from "node:path";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";

const evalRoot = resolve(import.meta.dirname, "..");
const sourceRoot = resolve(process.argv[2] ?? resolve(evalRoot, "../seedspec"));
const sourcePackage = resolve(sourceRoot, "packages/protocol");
const destination = resolve(evalRoot, "vendor/protocol");

const status = execFileSync("git", ["status", "--porcelain"], {
  cwd: sourceRoot,
  encoding: "utf8",
}).trim();
if (status.length > 0) {
  throw new Error(`Refusing to snapshot a dirty protocol checkout: ${sourceRoot}`);
}

const commit = execFileSync("git", ["rev-parse", "HEAD"], {
  cwd: sourceRoot,
  encoding: "utf8",
}).trim();
const packageJson = JSON.parse(await readFile(resolve(sourcePackage, "package.json"), "utf8"));
if (packageJson.name !== "@seedspec/protocol") {
  throw new Error(`Expected @seedspec/protocol at ${sourcePackage}`);
}

await rm(destination, { recursive: true, force: true });
await mkdir(destination, { recursive: true });
for (const entry of ["package.json", "README.md", "schemas", "src"]) {
  await cp(resolve(sourcePackage, entry), resolve(destination, entry), { recursive: true });
}

const sourceDigest = await digestDirectory(destination);

const snapshot = {
  schemaVersion: 1,
  package: packageJson.name,
  version: packageJson.version,
  sourceRepository: packageJson.repository?.url ?? null,
  sourceCommit: commit,
  sourceDigest,
  sourceDirectory: packageJson.repository?.directory ?? basename(sourcePackage),
};
await writeFile(resolve(destination, "snapshot.json"), `${JSON.stringify(snapshot, null, 2)}\n`, "utf8");
const generatedModule = `// Generated by scripts/sync-protocol.mjs. Do not edit manually.\nexport const FROZEN_PROTOCOL_SNAPSHOT = ${JSON.stringify(snapshot, null, 2)} as const;\n`;
for (const output of [
  resolve(evalRoot, "packages/cli/src/protocol-snapshot.generated.ts"),
  resolve(evalRoot, "apps/worker/src/protocol-snapshot.generated.ts"),
]) {
  await writeFile(output, generatedModule, "utf8");
}

process.stdout.write(`Synced ${packageJson.name}@${packageJson.version} from ${commit}.\n`);

async function digestDirectory(root) {
  const paths = [];
  await collect(root, "", paths);
  const aggregate = createHash("sha256");
  for (const relativePath of paths.toSorted()) {
    const bytes = await readFile(resolve(root, relativePath));
    const fileDigest = createHash("sha256").update(bytes).digest("hex");
    aggregate.update(`${relativePath}\0${fileDigest}\n`);
  }
  return `sha256:${aggregate.digest("hex")}`;
}

async function collect(root, relative, paths) {
  for (const entry of await readdir(resolve(root, relative), { withFileTypes: true })) {
    const next = relative.length === 0 ? entry.name : `${relative}/${entry.name}`;
    if (entry.isDirectory()) await collect(root, next, paths);
    else if (entry.isFile()) paths.push(next);
  }
}
